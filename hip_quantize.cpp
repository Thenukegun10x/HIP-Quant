static bool hip_check(hipError_t e, const char *what) {
    if (e == hipSuccess) return true;
    fprintf(stderr, "hip_quantize: %s failed: %s\n", what, hipGetErrorString(e));
    return false;
}

static void free_iq_tables(void ***ptrs, int count) {
    for (int i = 0; i < count; ++i) {
        if (*ptrs[i]) {
            hipFree(*ptrs[i]);
            *ptrs[i] = NULL;
        }
    }
}

static bool alloc_copy_table(void **dst, const void *src, size_t bytes, const char *name) {
    if (!hip_check(hipMalloc(dst, bytes), name)) return false;
    if (!hip_check(hipMemcpy(*dst, src, bytes, hipMemcpyHostToDevice), name)) {
        hipFree(*dst);
        *dst = NULL;
        return false;
    }
    return true;
}

static uint32_t iq_codebook_crc32(const uint8_t *data, size_t bytes) {
    uint32_t crc = 0xFFFFFFFFu;
    for (size_t i = 0; i < bytes; ++i) {
        crc ^= data[i];
        for (int bit = 0; bit < 8; ++bit) {
            crc = (crc >> 1) ^ (0xEDB88320u & (uint32_t)-(int32_t)(crc & 1u));
        }
    }
    return ~crc;
}

static bool iq_codebook_path(const char *name, char *path, size_t path_size) {
    const char *override_dir = getenv("HIP_QUANT_CODEBOOK_DIR");
    if (override_dir && override_dir[0]) {
        return snprintf(path, path_size, "%s/%s.bin", override_dir, name) > 0;
    }

    char module_path[4096] = {};
#if defined(_WIN32)
    HMODULE module = NULL;
    if (!GetModuleHandleExA(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS |
                            GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
                            (LPCSTR)&iq_codebook_path, &module)) {
        return false;
    }
    DWORD length = GetModuleFileNameA(module, module_path, (DWORD)sizeof(module_path));
    if (length == 0 || length >= sizeof(module_path)) return false;
#else
    Dl_info module_info = {};
    if (dladdr((void *)&iq_codebook_path, &module_info) == 0 || !module_info.dli_fname) return false;
    if (snprintf(module_path, sizeof(module_path), "%s", module_info.dli_fname) <= 0) return false;
#endif
    char *separator = strrchr(module_path, '/');
#if defined(_WIN32)
    char *backslash = strrchr(module_path, '\\');
    if (!separator || (backslash && backslash > separator)) separator = backslash;
#endif
    if (!separator) return false;
    *separator = '\0';
    return snprintf(path, path_size, "%s/codebooks/%s.bin", module_path, name) > 0;
}

static void free_iq_host_codebook(iq_host_codebook *table) {
    if (table->storage) free(table->storage);
    memset(table, 0, sizeof(*table));
}

static bool load_iq_host_codebook(
    const char *name, size_t grid_bytes, size_t map_bytes, size_t neighbours_bytes,
    iq_host_codebook *table
) {
    static const char expected_magic[8] = {'H', 'Q', 'I', 'Q', 'C', 'B', '0', '1'};
    char path[4096] = {};
    memset(table, 0, sizeof(*table));
    if (!iq_codebook_path(name, path, sizeof(path))) {
        fprintf(stderr, "hip_quantize: could not resolve I-Quant codebook path for %s\n", name);
        return false;
    }

    FILE *file = fopen(path, "rb");
    if (!file) {
        fprintf(stderr, "hip_quantize: missing I-Quant codebook %s (set HIP_QUANT_CODEBOOK_DIR to override)\n", path);
        return false;
    }

    iq_codebook_header header = {};
    const size_t payload_bytes = grid_bytes + map_bytes + neighbours_bytes;
    bool valid = fread(&header, 1, sizeof(header), file) == sizeof(header) &&
        memcmp(header.magic, expected_magic, sizeof(expected_magic)) == 0 &&
        header.version == 1 &&
        header.grid_bytes == grid_bytes &&
        header.map_bytes == map_bytes &&
        header.neighbours_bytes == neighbours_bytes;
    if (valid) {
        if (fseek(file, 0, SEEK_END) != 0 || ftell(file) != (long)(sizeof(header) + payload_bytes) ||
            fseek(file, sizeof(header), SEEK_SET) != 0) {
            valid = false;
        }
    }
    if (!valid) {
        fprintf(stderr, "hip_quantize: invalid I-Quant codebook header in %s\n", path);
        fclose(file);
        return false;
    }

    uint8_t *storage = (uint8_t *)malloc(payload_bytes);
    if (!storage || fread(storage, 1, payload_bytes, file) != payload_bytes ||
        iq_codebook_crc32(storage, payload_bytes) != header.crc32) {
        fprintf(stderr, "hip_quantize: corrupt or unreadable I-Quant codebook %s\n", path);
        if (storage) free(storage);
        fclose(file);
        return false;
    }
    fclose(file);
    table->storage = storage;
    table->grid = storage;
    table->map = storage + grid_bytes;
    table->neighbours = storage + grid_bytes + map_bytes;
    return true;
}

static bool ensure_initialized() {
    if (!hip_initialized) {
        int count = 0;
        if (!hip_check(hipGetDeviceCount(&count), "hipGetDeviceCount")) return false;
        if (count <= 0) {
            fprintf(stderr, "hip_quantize: no HIP devices available\n");
            return false;
        }
        device_id = 0;
        int best_cu = 0;
        for (int i = 0; i < count; i++) {
            hipDeviceProp_t p;
            if (!hip_check(hipGetDeviceProperties(&p, i), "hipGetDeviceProperties")) return false;
            if (p.multiProcessorCount > best_cu) {
                best_cu = p.multiProcessorCount;
                device_id = i;
            }
        }
        if (!hip_check(hipSetDevice(device_id), "hipSetDevice")) return false;
        if (!hip_check(hipGetDeviceProperties(&props, device_id), "hipGetDeviceProperties")) return false;
        hip_initialized = true;
    }
    if (!iq3xxs_tables_loaded) {
        iq_host_codebook table = {};
        if (!load_iq_host_codebook("iq3_xxs", 256 * 4, 4096 * sizeof(int), 22825 * sizeof(uint16_t), &table)) return false;
        bool copied =
            hip_check(hipMemcpyToSymbol(HIP_SYMBOL(d_iq3xxs_grid), table.grid, 256 * 4), "copy iq3xxs grid") &&
            hip_check(hipMemcpyToSymbol(HIP_SYMBOL(d_iq3xxs_map), table.map, 4096 * sizeof(int)), "copy iq3xxs map") &&
            hip_check(hipMemcpyToSymbol(HIP_SYMBOL(d_iq3xxs_neighbours), table.neighbours, 22825 * sizeof(uint16_t)), "copy iq3xxs neighbours");
        free_iq_host_codebook(&table);
        if (!copied) return false;
        iq3xxs_tables_loaded = true;
    }
    if (!iq2xxs_tables_loaded) {
        void **ptrs[] = {(void **)&d_iq2xxs_map_data, (void **)&d_iq2xxs_neighbours_data};
        iq_host_codebook table = {};
        if (!load_iq_host_codebook("iq2_xxs", 256 * 8, 43692 * sizeof(int), 417400 * sizeof(uint16_t), &table)) return false;
        bool copied = hip_check(hipMemcpyToSymbol(HIP_SYMBOL(d_iq2xxs_grid), table.grid, 256 * 8), "copy iq2xxs grid") &&
            alloc_copy_table((void **)&d_iq2xxs_map_data, table.map, 43692 * sizeof(int), "copy iq2xxs map") &&
            alloc_copy_table((void **)&d_iq2xxs_neighbours_data, table.neighbours, 417400 * sizeof(uint16_t), "copy iq2xxs neighbours");
        free_iq_host_codebook(&table);
        if (!copied) { free_iq_tables(ptrs, 2); return false; }
        iq2xxs_tables_loaded = true;
    }
    if (!iq2xs_tables_loaded) {
        void **ptrs[] = {(void **)&d_iq2xs_grid_data, (void **)&d_iq2xs_map_data, (void **)&d_iq2xs_neighbours_data};
        iq_host_codebook table = {};
        if (!load_iq_host_codebook("iq2_xs", 512 * 8, 43692 * sizeof(int), 551722 * sizeof(uint16_t), &table)) return false;
        bool copied =
            alloc_copy_table((void **)&d_iq2xs_grid_data, table.grid, 512 * 8, "copy iq2xs grid") &&
            alloc_copy_table((void **)&d_iq2xs_map_data, table.map, 43692 * sizeof(int), "copy iq2xs map") &&
            alloc_copy_table((void **)&d_iq2xs_neighbours_data, table.neighbours, 551722 * sizeof(uint16_t), "copy iq2xs neighbours");
        free_iq_host_codebook(&table);
        if (!copied) { free_iq_tables(ptrs, 3); return false; }
        iq2xs_tables_loaded = true;
    }
    if (!iq1s_tables_loaded) {
        void **ptrs[] = {(void **)&d_iq1s_grid_data, (void **)&d_iq1s_map_data, (void **)&d_iq1s_neighbours_data};
        iq_host_codebook table = {};
        if (!load_iq_host_codebook("iq1_s", 2048 * 8, 43692 * sizeof(int), 1375339 * sizeof(uint16_t), &table)) return false;
        bool copied =
            alloc_copy_table((void **)&d_iq1s_grid_data, table.grid, 2048 * 8, "copy iq1s grid") &&
            alloc_copy_table((void **)&d_iq1s_map_data, table.map, 43692 * sizeof(int), "copy iq1s map") &&
            alloc_copy_table((void **)&d_iq1s_neighbours_data, table.neighbours, 1375339 * sizeof(uint16_t), "copy iq1s neighbours");
        free_iq_host_codebook(&table);
        if (!copied) { free_iq_tables(ptrs, 3); return false; }
        iq1s_tables_loaded = true;
    }
    if (!iq3s_tables_loaded) {
        void **ptrs[] = {(void **)&d_iq3s_grid_data, (void **)&d_iq3s_map_data, (void **)&d_iq3s_neighbours_data};
        iq_host_codebook table = {};
        if (!load_iq_host_codebook("iq3_s", 512 * 4, 4096 * sizeof(int), 28317 * sizeof(uint16_t), &table)) return false;
        bool copied =
            alloc_copy_table((void **)&d_iq3s_grid_data, table.grid, 512 * 4, "copy iq3s grid") &&
            alloc_copy_table((void **)&d_iq3s_map_data, table.map, 4096 * sizeof(int), "copy iq3s map") &&
            alloc_copy_table((void **)&d_iq3s_neighbours_data, table.neighbours, 28317 * sizeof(uint16_t), "copy iq3s neighbours");
        free_iq_host_codebook(&table);
        if (!copied) { free_iq_tables(ptrs, 3); return false; }
        iq3s_tables_loaded = true;
    }
    return true;
}

