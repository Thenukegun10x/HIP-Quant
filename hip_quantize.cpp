// I-Quant codebooks are runtime assets rather than giant compile-time C++
// arrays.  This keeps the DLL small and lets package updates replace table
// data without recompiling device code.  The binary layout is generated by
// tools/export_iq_codebooks.py and is intentionally little-endian.
#pragma pack(push, 1)
typedef struct {
    char magic[8];
    uint32_t version;
    uint32_t grid_bytes;
    uint32_t map_bytes;
    uint32_t neighbours_bytes;
    uint32_t crc32;
} iq_codebook_header;
#pragma pack(pop)

typedef struct {
    void *storage;
    void *grid;
    void *map;
    void *neighbours;
} iq_host_codebook;

static_assert(sizeof(int) == 4, "external I-Quant maps require 32-bit int");
static_assert(sizeof(iq_codebook_header) == 28, "unexpected I-Quant codebook header layout");

